export function originTemplate(seed){return ORIGINS[(Number(seed)>>>0)%ORIGINS.length];}
export function chooseBirthplace(s){
  if(!enabled(s,'origins'))return Object.values(s.areas).find(isTown)?.id||'a0';
  const safe=Object.values(s.areas).filter(a=>!a.temporaryCamp&&(isTown(a)||a.type==='camp'||a.type==='road')&&!a.objects.some(o=>o.kind==='enemy'&&o.alive&&!o.resolved)&&a.era===0);
  if(s.generation===1)return ['a1','a0','a4'][s.seed%3];
  return safe.length?safe[Math.floor(moduleRandom(s,'origins')*safe.length)].id:'a1';
}
